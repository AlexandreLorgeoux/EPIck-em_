import { describe, expect, it } from '@jest/globals';
import { BadRequestException } from '@nestjs/common';
import { uuidParam } from './uuid-param.pipe.js';

const metadata = { type: 'param', data: 'id' } as const;

describe('uuidParam', () => {
  it('accepts the UUIDv7 ids generated by the database', async () => {
    const id = '0190a7c0-1234-7abc-8def-0123456789ab';
    await expect(uuidParam().transform(id, metadata)).resolves.toBe(id);
  });

  it('rejects anything else with 400 and names the parameter', async () => {
    const run = uuidParam('playerId').transform('not-a-uuid', metadata);
    await expect(run).rejects.toThrow(BadRequestException);
    await expect(
      uuidParam('playerId').transform('42', metadata),
    ).rejects.toThrow('playerId must be a valid UUID');
  });
});
